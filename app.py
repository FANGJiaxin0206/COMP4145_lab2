import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from trading_strategy import (
    calculate_moving_averages,
    get_stock_data,
    identify_golden_cross,
    implement_strategy,
)


st.set_page_config(
    page_title="Trading Strategy Dashboard",
    page_icon="📈",
    layout="wide",
)


@st.cache_data
def load_strategy_data():
    data = get_stock_data("MSFT")
    if data.empty:
        return data, pd.DataFrame(
            columns=[
                "BuyDate",
                "BuyPrice",
                "SellDate",
                "SellPrice",
                "HoldingDays",
                "ProfitPct",
                "SellReason",
            ]
        )

    data = calculate_moving_averages(data)
    data = identify_golden_cross(data)
    positions = implement_strategy(data)

    if not positions.empty:
        positions = positions.reset_index(drop=True)

    return data, positions


page = st.sidebar.radio(
    "Navigation",
    ["Price Chart", "Trade Statistics", "Detailed Trades"],
    index=0,
)


data, positions = load_strategy_data()

if page == "Price Chart":
    st.title("Price Chart and Trading Signals")

    if data.empty:
        st.warning("No stock data available for MSFT.")
    else:
        chart_data = data.reset_index().rename(columns={"Date": "Date"})
        chart_data["Date"] = pd.to_datetime(chart_data.index)

        fig = go.Figure()
        fig.add_trace(
            go.Scatter(
                x=chart_data.index,
                y=chart_data["Close"],
                mode="lines",
                name="Stock Price",
                line={"color": "#1f77b4", "width": 2},
            )
        )
        fig.add_trace(
            go.Scatter(
                x=chart_data.index,
                y=chart_data["MA50"],
                mode="lines",
                name="MA50",
                line={"color": "#ff7f0e", "width": 2},
            )
        )
        fig.add_trace(
            go.Scatter(
                x=chart_data.index,
                y=chart_data["MA200"],
                mode="lines",
                name="MA200",
                line={"color": "#d62728", "width": 2},
            )
        )

        if not positions.empty:
            buy_dates = pd.to_datetime(positions["BuyDate"])
            sell_dates = pd.to_datetime(positions["SellDate"])
            buy_prices = positions["BuyPrice"].astype(float)
            sell_prices = positions["SellPrice"].astype(float)

            fig.add_trace(
                go.Scatter(
                    x=buy_dates,
                    y=buy_prices,
                    mode="markers",
                    name="Buy",
                    marker={"size": 10, "color": "green", "symbol": "circle"},
                )
            )
            fig.add_trace(
                go.Scatter(
                    x=sell_dates,
                    y=sell_prices,
                    mode="markers",
                    name="Sell",
                    marker={"size": 10, "color": "red", "symbol": "diamond"},
                )
            )

        fig.update_layout(
            title="MSFT Price with MA50 and MA200",
            xaxis_title="Date",
            yaxis_title="Price (USD)",
            template="plotly_white",
            legend={"orientation": "h", "yanchor": "bottom", "y": 1.02, "xanchor": "left", "x": 0},
            hovermode="x unified",
        )

        st.plotly_chart(fig, use_container_width=True)

elif page == "Trade Statistics":
    st.title("Overall Trade Statistics")

    if positions.empty:
        st.info("No trades were generated by the strategy for the selected stock and time period.")
    else:
        total_trades = len(positions)
        win_trades = int((positions["ProfitPct"] > 0).sum())
        loss_trades = total_trades - win_trades
        win_rate = (win_trades / total_trades) * 100 if total_trades else 0
        avg_profit = positions["ProfitPct"].mean()
        avg_holding = positions["HoldingDays"].mean()
        total_profit = positions["ProfitPct"].sum()

        col1, col2, col3, col4 = st.columns(4)
        col1.metric("Total Trades", total_trades)
        col2.metric("Winning Trades", win_trades)
        col3.metric("Lossing Trades", loss_trades)
        col4.metric("Win Rate", f"{win_rate:.2f}%")

        col5, col6, col7, col8 = st.columns(4)
        col5.metric("Average Profit %", f"{avg_profit:.2f}%")
        col6.metric("Total Profit %", f"{total_profit:.2f}%")
        col7.metric("Average Holding Days", f"{avg_holding:.2f}")
        col8.metric("Target Reached", int((positions["SellReason"] == "Target reached").sum()))

        summary_df = pd.DataFrame(
            [
                {"Metric": "Total Trades", "Value": total_trades},
                {"Metric": "Winning Trades", "Value": win_trades},
                {"Metric": "Losing Trades", "Value": loss_trades},
                {"Metric": "Win Rate (%)", "Value": round(win_rate, 2)},
                {"Metric": "Average Profit (%)", "Value": round(avg_profit, 2)},
                {"Metric": "Total Profit (%)", "Value": round(total_profit, 2)},
                {"Metric": "Average Holding Days", "Value": round(avg_holding, 2)},
            ]
        )

        st.dataframe(summary_df, use_container_width=True, hide_index=True)

else:
    st.title("Detailed Trade Records")

    if positions.empty:
        st.info("No detailed trade records are available.")
    else:
        display_df = positions.copy()
        display_df["BuyDate"] = pd.to_datetime(display_df["BuyDate"]).dt.strftime("%Y-%m-%d")
        display_df["SellDate"] = pd.to_datetime(display_df["SellDate"]).dt.strftime("%Y-%m-%d")
        display_df["BuyPrice"] = display_df["BuyPrice"].map(lambda x: f"${x:,.2f}")
        display_df["SellPrice"] = display_df["SellPrice"].map(lambda x: f"${x:,.2f}")
        display_df["ProfitPct"] = display_df["ProfitPct"].map(lambda x: f"{x:.2f}%")

        st.dataframe(display_df, use_container_width=True, hide_index=True)
